package ru.yandex.practicum.mymarket.service;

/**
 * Картинка с таким ключом в хранилище отсутствует.
 *
 * <p>Отдельный тип нужен, чтобы отличить «картинки нет» от «хранилище недоступно».
 * Первое — штатный ответ 404, второе — сбой, который должен попасть в лог как
 * инцидент и отдаться 500. Без разделения пропажа картинки выглядела бы как
 * поломка сервиса: в лог сыпалась бы ошибка хранилища, хотя хранилище работает.
 *
 * <p>Ошибка обязана возникать <em>до</em> отправки ответа. Поток с содержимым
 * картинки подписывается уже после того, как статус и заголовки отправлены
 * клиенту, и ошибка в нём уже не позволяет сменить статус: вместо 404 ушёл бы
 * 200 с оборванным телом. Поэтому хранилище опрашивается при сборке ответа, а
 * не в момент записи тела.
 */
public class ImageNotFoundException extends RuntimeException {

    /**
     * @param key ключ, которого нет в хранилище
     */
    public ImageNotFoundException(String key) {
        super("Картинка с ключом '" + key + "' не найдена в хранилище");
    }
}
