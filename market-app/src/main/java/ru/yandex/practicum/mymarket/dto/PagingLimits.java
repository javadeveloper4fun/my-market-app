package ru.yandex.practicum.mymarket.dto;

/**
 * Пределы пагинации, общие для выбора данных и формирования представления.
 *
 * <p>Константа вынесена отдельно, чтобы сервис и {@link Paging} использовали
 * одно и то же значение: иначе при смене максимума они разъедутся, и страница
 * будет посчитана некорректно.
 */
public final class PagingLimits {

    /** Максимальный размер страницы: совпадает с доступными значениями в UI. */
    public static final int MAX_PAGE_SIZE = 100;

    private PagingLimits() {}
}
